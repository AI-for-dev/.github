"""Regenerate every file in profile/brand from one geometry and one font.

    uv run --with fonttools python tools/build-brand.py

The mark, the lockup and the map all draw the same harness: four corner pieces in the
ink, one square in the accent. Writing them from a single script keeps them from
drifting apart, and outlining the words here means no SVG depends on a font the reader
may not have. GitHub renders these files through <img>, where no web font can load.

The font is vendored under tools/fonts, with its licence, and its digest is checked before
a glyph is read: a wordmark outlined from the wrong typeface does not look wrong.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "tools" / "fonts" / "JetBrainsMono-Regular.ttf"
# JetBrains Mono 2.304, unmodified, the same file trysquare outlines its wordmark from.
FONT_SHA256 = "a0bf60ef0f83c5ed4d7a75d45838548b1f6873372dfac88f71804491898d138f"
OUT = ROOT / "profile" / "brand"

# Slate and paper are trysquare's and combo's neutrals. The accent is the sanguine of the
# course slides, lifted a step on the dark ground so it does not go brown.
THEMES = {
    "light": {"ink": "#232B33", "muted": "#56616B", "accent": "#B4472A"},
    "dark": {"ink": "#C9D3DB", "muted": "#8E9BA5", "accent": "#E2805F"},
}
SLATE, PAPER = "#232B33", "#EEF1F3"


# --- The mark ---------------------------------------------------------------------------
# On a 64-unit grid, the artwork spans 8..56 on both axes. Corner pieces are L-shapes with
# arms of 14 and a thickness of 5; the square is 18 and sits in the exact centre, so the
# gap between it and each corner is the same on all four sides.

def corners(x0: float, y0: float, size: float, arm: float, t: float) -> list[tuple]:
    x1, y1 = x0 + size, y0 + size
    return [
        (x0, y0, arm, t), (x0, y0, t, arm),
        (x1 - arm, y0, arm, t), (x1 - t, y0, t, arm),
        (x0, y1 - t, arm, t), (x0, y1 - arm, t, arm),
        (x1 - arm, y1 - t, arm, t), (x1 - t, y1 - arm, t, arm),
    ]


def rects(boxes: list[tuple], fill: str, indent: str = "    ") -> str:
    body = "\n".join(
        f'{indent}  <rect x="{fmt(x)}" y="{fmt(y)}" width="{fmt(w)}" height="{fmt(h)}" />'
        for x, y, w, h in boxes
    )
    return f'{indent}<g fill="{fill}">\n{body}\n{indent}</g>'


def square(cx: float, cy: float, size: float, fill: str, indent: str = "    ") -> str:
    h = size / 2
    return (f'{indent}<rect fill="{fill}" x="{fmt(cx - h)}" y="{fmt(cy - h)}" '
            f'width="{fmt(size)}" height="{fmt(size)}" />')


def mark_body(ink: str, accent: str, indent: str = "  ") -> str:
    return rects(corners(8, 8, 48, 14, 5), ink, indent) + "\n" + square(32, 32, 18, accent, indent)


def fmt(v: float) -> str:
    return f"{v:.4g}"


def mark(theme: str, ink: str, accent: str) -> str:
    ground = "a light" if theme == "light" else "a dark"
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64" role="img" aria-label="AI for dev">
  <title>AI for dev</title>
  <!-- The mark for {ground} ground. Generated by tools/build-brand.py - edit the script,
       not the coordinates. -->
{mark_body(ink, accent)}
</svg>
"""


def mark_current() -> str:
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64" role="img" aria-label="AI for dev">
  <title>AI for dev</title>
  <!-- For inlining only: the corners follow the surrounding text colour. currentColor
       does not cross an <img> boundary, so anything referenced by src picks the light
       or dark file. Generated by tools/build-brand.py. -->
{mark_body("currentColor", THEMES["light"]["accent"])}
</svg>
"""


def tile() -> str:
    # Thicker corners and a larger square: at 16px the regular mark's 5-unit arms become a
    # single pixel and start to shimmer. The ground is the slate, so the tile carries its
    # own contrast in a light or a dark tab bar.
    body = rects(corners(10, 10, 44, 15, 7), PAPER) + "\n" + square(32, 32, 16, THEMES["dark"]["accent"])
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64" role="img" aria-label="AI for dev">
  <title>AI for dev</title>
  <!-- The tile: favicon, avatar, and anywhere the mark needs a ground of its own.
       Generated by tools/build-brand.py. -->
  <rect width="64" height="64" rx="12" fill="{SLATE}" />
{body}
</svg>
"""


def avatar_html() -> str:
    """A page that paints the avatar at 512px, for a headless browser to screenshot.

    GitHub only accepts a raster avatar, and an organisation avatar is shown with rounded
    corners of its own, so the ground runs to the edge here instead of carrying rx.
    """
    body = rects(corners(10, 10, 44, 15, 7), PAPER, "  ") + "\n" + square(32, 32, 16, THEMES["dark"]["accent"], "  ")
    return f"""<!doctype html><meta charset="utf-8">
<style>html,body{{margin:0;background:{SLATE}}}svg{{display:block}}</style>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="512" height="512">
  <rect width="64" height="64" fill="{SLATE}" />
{body}
</svg>
"""


# --- Words ------------------------------------------------------------------------------

class Type:
    def __init__(self, font: TTFont) -> None:
        self.font = font
        self.upem = font["head"].unitsPerEm
        self.glyphs = font.getGlyphSet()
        self.cmap = font.getBestCmap()
        self.hmtx = font["hmtx"]
        self.x_height = font["OS/2"].sxHeight
        self.cap_height = font["OS/2"].sCapHeight

    def outline(self, word: str, size: float, tracking: float = 0.0) -> tuple[str, float]:
        """The word as one path in font units, and its advance in px at `size`."""
        track = tracking * self.upem / size
        parts, x = [], 0.0
        for char in word:
            name = self.cmap[ord(char)]
            pen = SVGPathPen(self.glyphs)
            self.glyphs[name].draw(TransformPen(pen, (1, 0, 0, 1, x, 0)))
            if commands := pen.getCommands():
                parts.append(commands)
            x += self.hmtx[name][0] + track
        return " ".join(parts), (x - track) * size / self.upem

    def path(self, word: str, x: float, baseline: float, size: float, fill: str,
             tracking: float = 0.0, anchor: str = "start") -> str:
        d, advance = self.outline(word, size, tracking)
        if anchor == "end":
            x -= advance
        s = size / self.upem
        return (f'  <path fill="{fill}" transform="translate({fmt(x)} {fmt(baseline)}) '
                f'scale({s:.6g} -{s:.6g})"\n        d="{d}" />')


# --- The lockup -------------------------------------------------------------------------
# The mark at 0.7 so its artwork is 33.6px tall, the height of trysquare's and combo's
# marks in their own lockups. The word is set like trysquare's: 25px, 0.5px tracking, and
# centred on the x-height band, because a lower-case word is read from its x-height.

WORD, WORD_SIZE, WORD_TRACKING = "ai-for-dev", 25.0, 0.5
MARK_SCALE, MARK_DX = 0.7, 2.0
MARK_DY = 32 - 32 * MARK_SCALE
GAP_EM = 0.5


def lockup(t: Type, theme: str, ink: str, accent: str) -> str:
    mark_left = MARK_DX + 8 * MARK_SCALE
    mark_right = MARK_DX + 56 * MARK_SCALE
    text_x = mark_right + GAP_EM * WORD_SIZE
    baseline = 32 + t.x_height * WORD_SIZE / t.upem / 2
    _, advance = t.outline(WORD, WORD_SIZE, WORD_TRACKING)
    width = round(text_x + advance + mark_left)
    word = t.path(WORD, text_x, baseline, WORD_SIZE, ink, WORD_TRACKING)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} 64" width="{width}" height="64" role="img" aria-label="ai-for-dev">
  <title>ai-for-dev</title>
  <!-- Horizontal lockup for a {theme} ground, wordmark outlined from {FONT.name}
       ({WORD_SIZE:g}px, {WORD_TRACKING:g}px tracking). Generated by tools/build-brand.py -
       edit the script, not the path data. -->
  <g transform="translate({fmt(MARK_DX)} {fmt(MARK_DY)}) scale({MARK_SCALE})">
{mark_body(ink, accent, "    ")}
  </g>
{word}
</svg>
"""


# --- The map ----------------------------------------------------------------------------
# The mark drawn large, with each corner labelled by the repository that builds that part
# of the harness, and the square left as what it is: the model, the one piece nobody here
# writes. Background is transparent so the file sits on GitHub's own ground.

MAP_W, MAP_H = 960, 380
FRAME, ARM, THICK = 260, 54, 10
CORE = 78
NAME_SIZE, NOTE_SIZE = 21.0, 15.0
LABEL_GAP = 30  # from the frame's edge to the nearest letter

CORNERS = [
    # (side, row, repository, what it builds)
    ("left", "top", "hands-on-harness", "the course: context, skills, hooks"),
    ("right", "top", "combo", "subagents, chained by code"),
    ("left", "bottom", "ai4dev-pi-kit", "a sandbox for unattended runs"),
    ("right", "bottom", "trysquare", "does the difference hold?"),
]


def map_svg(t: Type, theme: str, ink: str, muted: str, accent: str) -> str:
    x0, y0 = (MAP_W - FRAME) / 2, (MAP_H - FRAME) / 2
    x1, y1 = x0 + FRAME, y0 + FRAME
    cx, cy = MAP_W / 2, MAP_H / 2
    cap_name = t.cap_height * NAME_SIZE / t.upem
    parts = [rects(corners(x0, y0, FRAME, ARM, THICK), ink, "  "), square(cx, cy, CORE, accent, "  ")]

    for side, row, name, note in CORNERS:
        x = x0 - LABEL_GAP if side == "left" else x1 + LABEL_GAP
        anchor = "end" if side == "left" else "start"
        # The name's cap height sits flush with the outer edge of the corner, the note
        # hangs below it; on the bottom row the pair is mirrored so the note's baseline
        # sits on the frame's bottom edge.
        if row == "top":
            name_base = y0 + cap_name
            note_base = name_base + 26
        else:
            note_base = y1
            name_base = note_base - 26
        parts.append(t.path(name, x, name_base, NAME_SIZE, ink, anchor=anchor))
        parts.append(t.path(note, x, note_base, NOTE_SIZE, muted, anchor=anchor))

    label = "the model"
    _, advance = t.outline(label, NOTE_SIZE)
    parts.append(t.path(label, cx - advance / 2, cy + CORE / 2 + 24, NOTE_SIZE, muted))

    body = "\n".join(parts)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {MAP_W} {MAP_H}" width="{MAP_W}" height="{MAP_H}" role="img" aria-label="The four repositories of AI for dev, placed on the four corners of the harness around the model">
  <title>The harness, and who builds which part of it</title>
  <!-- For a {theme} ground. Generated by tools/build-brand.py - edit the script, not the
       path data. -->
{body}
</svg>
"""


def main() -> None:
    digest = hashlib.sha256(FONT.read_bytes()).hexdigest()
    if digest != FONT_SHA256:
        raise SystemExit(
            f"{FONT.name} is not the font this brand was drawn with.\n"
            f"  expected {FONT_SHA256}\n  found    {digest}"
        )
    t = Type(TTFont(FONT))
    OUT.mkdir(parents=True, exist_ok=True)

    files = {"ai-for-dev-mark.svg": mark_current(), "ai-for-dev-tile.svg": tile()}
    for theme, c in THEMES.items():
        files[f"ai-for-dev-mark-{theme}.svg"] = mark(theme, c["ink"], c["accent"])
        files[f"ai-for-dev-lockup-{theme}.svg"] = lockup(t, theme, c["ink"], c["accent"])
        files[f"ai-for-dev-map-{theme}.svg"] = map_svg(t, theme, c["ink"], c["muted"], c["accent"])

    for name, text in files.items():
        (OUT / name).write_text(text, encoding="utf-8")
        print(f"profile/brand/{name}")

    avatar = ROOT / "tools" / "avatar.html"
    avatar.write_text(avatar_html(), encoding="utf-8")
    print("tools/avatar.html  (screenshot it at 512x512 into profile/brand/ai-for-dev-avatar.png)")


if __name__ == "__main__":
    main()
